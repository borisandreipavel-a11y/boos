// Finds the picture of a sign.
pub fn letter_shape(sign: char) -> &'static Shape {
    let number = sign as u32;
    if (32..=126).contains(&number) {
        &SHAPES[(number - 32) as usize]
    } else {
        &UNKNOWN
    }
}
