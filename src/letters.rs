//! The shapes of the letters, digits and signs, drawn by hand as small grids
//! of dots. Notes: `docs/screen.md`.

// The screen only knows dots, so every sign needs a small picture of itself.
// Here a picture is 5 dots across and 9 down. A `#` is a dot that gets
// painted, a `.` is one that is left alone. The first seven rows hold the
// sign. The last two are for the tails of letters such as g, p and y, which
// hang below the line of writing.
pub const LETTER_WIDTH: u32 = 5;
pub const LETTER_HEIGHT: u32 = 9;
pub type Shape = [[u8; LETTER_WIDTH as usize]; LETTER_HEIGHT as usize];

// To change the look of a sign, change its picture below. Every row must
// stay 5 signs long and every picture 9 rows high, or the kernel is not built.

